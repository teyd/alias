/**
 * Vendors the tracker lists forwarded mail is cleaned with (PLAN.md §20.19) into
 * `packages/core/src/internal/lists/`, pinned to a commit and with their licence:
 *
 * - EasyPrivacy's email tracker rules (GPL-3.0-or-later, dual-licensed with CC BY-SA 3.0+; we use
 *   the GPL option, which may be combined with AGPL-3.0);
 * - Brave's query filter, the click-tracking parameters Brave strips (MPL-2.0; the file stays
 *   under the MPL, as MPL-2.0 §3.3 requires, inside the AGPL work).
 *
 * Usage: `node scripts/refresh-tracker-lists.ts` takes the latest commit that changed each file;
 * `--easyprivacy <sha>` / `--brave <sha>` pin one. Fails on a rule the core matcher doesn't
 * understand, instead of writing a list that would silently match less. Review the diff, run
 * `pnpm --filter @alias/core test`, and commit the result.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { worktreeRoot } from "./lib/worktree.ts";

interface Source {
  readonly repo: string;
  readonly path: string;
  readonly flag: string;
}

const EASYPRIVACY: Source = {
  repo: "easylist/easylist",
  path: "easyprivacy/easyprivacy_general_emailtrackers.txt",
  flag: "--easyprivacy",
};
const BRAVE: Source = {
  repo: "brave/adblock-lists",
  path: "brave-lists/query-filter.json",
  flag: "--brave",
};

const args = process.argv.slice(2);
const outDir = join(worktreeRoot(), "packages/core/src/internal/lists");

const get = async (url: string): Promise<string> => {
  const response = await fetch(url, { headers: { "user-agent": "alias-refresh-tracker-lists" } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
};

/** The pinned commit: the flag's value, or the latest commit that changed the file. */
const resolve = async (source: Source): Promise<{ sha: string; date: string }> => {
  const index = args.indexOf(source.flag);
  const pinned = index === -1 ? undefined : args[index + 1];
  const query = pinned === undefined ? `?path=${source.path}&per_page=1` : `/${pinned}`;
  const body = JSON.parse(
    await get(`https://api.github.com/repos/${source.repo}/commits${query}`),
  ) as unknown;
  const commit = (Array.isArray(body) ? body[0] : body) as
    | { sha: string; commit: { committer: { date: string } } }
    | undefined;
  if (commit === undefined) throw new Error(`${source.repo}: no commit found`);
  return { sha: commit.sha, date: commit.commit.committer.date.slice(0, 10) };
};

const raw = (source: Source, sha: string) =>
  get(`https://raw.githubusercontent.com/${source.repo}/${sha}/${source.path}`);

/** The Adblock Plus subset `filters.ts` implements: substring patterns with `*` and `^`. */
const isSupportedRule = (rule: string): boolean => {
  const [pattern = "", options, ...more] = rule.split("$");
  const isRegExp = pattern.length > 1 && pattern.startsWith("/") && pattern.endsWith("/");
  const isOtherSyntax = /^(?:\||@@)|#[@?$]?#/.test(pattern);
  const isKnownOption = (option: string) => option === "image" || option === "third-party";
  return (
    pattern.length > 0 &&
    !isRegExp &&
    !isOtherSyntax &&
    more.length === 0 &&
    (options === undefined || options.split(",").every(isKnownOption))
  );
};

const literal = (value: string) => JSON.stringify(value);

const writeEasyPrivacy = async () => {
  const { sha, date } = await resolve(EASYPRIVACY);
  const rules = (await raw(EASYPRIVACY, sha))
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("!") && !line.startsWith("["));
  const unsupported = rules.filter((rule) => !isSupportedRule(rule));
  if (unsupported.length > 0) {
    throw new Error(`EasyPrivacy rules filters.ts can't match:\n${unsupported.join("\n")}`);
  }
  writeFileSync(
    join(outDir, "easyprivacy.ts"),
    `/**
 * Generated by \`node scripts/refresh-tracker-lists.ts\`; do not edit.
 *
 * EasyPrivacy email tracker rules, from
 * https://github.com/${EASYPRIVACY.repo}/blob/${sha}/${EASYPRIVACY.path}
 * (commit ${sha}, ${date}). Adblock Plus syntax; \`filters.ts\` matches them.
 *
 * Copyright The EasyList authors (https://easylist.to/). Licensed under the GNU General Public
 * License version 3 or (at your option) any later version, one of the two licences the EasyList
 * authors offer (https://easylist.to/pages/licence.html).
 */
export const rules: ReadonlyArray<string> = [
${rules.map((rule) => `  ${literal(rule)},`).join("\n")}
];
`,
  );
  console.log(`easyprivacy.ts: ${rules.length} rules at ${sha} (${date})`);
};

interface QueryGroup {
  readonly include: ReadonlyArray<string>;
  readonly exclude: ReadonlyArray<string>;
  readonly params: ReadonlyArray<string>;
}

// Include patterns filters.ts understands: any host, one host, or a host and its subdomains
// (`*://` + `*`, `host` or `*.host` + `/*`).
const isSupportedPattern = (pattern: string) =>
  /^\*:\/\/(?:\*|(?:\*\.)?[a-z0-9.-]+)\/\*$/.test(pattern);

const writeBrave = async () => {
  const { sha, date } = await resolve(BRAVE);
  const groups = JSON.parse(await raw(BRAVE, sha)) as ReadonlyArray<QueryGroup>;
  const unsupported = groups.filter(
    (group) => group.exclude.length > 0 || !group.include.every(isSupportedPattern),
  );
  if (unsupported.length > 0) {
    throw new Error(`Brave query groups filters.ts can't match:\n${JSON.stringify(unsupported)}`);
  }
  const strings = (values: ReadonlyArray<string>) =>
    values.map((value) => `      ${literal(value)},`).join("\n");
  writeFileSync(
    join(outDir, "brave.ts"),
    `/**
 * Generated by \`node scripts/refresh-tracker-lists.ts\`; do not edit.
 *
 * Brave's query filter: the click-tracking parameters Brave removes from links, for the sites in
 * \`include\`. From https://github.com/${BRAVE.repo}/blob/${sha}/${BRAVE.path}
 * (commit ${sha}, ${date}); \`filters.ts\` matches them.
 *
 * This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy
 * of the MPL was not distributed with this file, You can obtain one at
 * https://mozilla.org/MPL/2.0/.
 */
export const groups: ReadonlyArray<{
  readonly include: ReadonlyArray<string>;
  readonly params: ReadonlyArray<string>;
}> = [
${groups
  .map(
    (group) => `  {
    include: [
${strings(group.include)}
    ],
    params: [
${strings(group.params)}
    ],
  },`,
  )
  .join("\n")}
];
`,
  );
  console.log(`brave.ts: ${groups.length} groups at ${sha} (${date})`);
};

await writeEasyPrivacy();
await writeBrave();
execFileSync("pnpm", ["exec", "vp", "fmt", outDir], { stdio: "inherit" });
