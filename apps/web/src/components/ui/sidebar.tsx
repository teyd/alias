import * as React from "react";
import { mergeProps } from "@base-ui/react/merge-props";
import { useRender } from "@base-ui/react/use-render";
import { cn } from "cn";

/*
 * shadcn's base-nova sidebar, cut down to its static (`collapsible="none"`) form: no provider,
 * no open state, no cookie, no keyboard shortcut. The app shell hides it below `md` and shows
 * the same navigation in a sheet instead.
 */

function Sidebar({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="sidebar"
      className={cn("flex h-full w-64 flex-col bg-sidebar text-sidebar-foreground", className)}
      {...props}
    />
  );
}

