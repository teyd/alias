import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const devEnvPath = (root: string): string => join(root, ".dev", "env");

export const writeDevEnv = (root: string, values: Record<string, string>): void => {
  mkdirSync(join(root, ".dev"), { recursive: true });
  const body = Object.entries(values)
    .map(([key, value]) => `${key}=${value}`)
    .join("\n");
  writeFileSync(devEnvPath(root), `# generated by \`pnpm agent:setup\`; do not edit\n${body}\n`);
};

export const readDevEnv = (root: string): Record<string, string> => {
  const path = devEnvPath(root);
  if (!existsSync(path)) {
    throw new Error("Missing .dev/env. Run `pnpm agent:setup` first.");
  }
  return Object.fromEntries(
    readFileSync(path, "utf8")
      .split("\n")
      .filter((line) => line.length > 0 && !line.startsWith("#"))
      .map((line) => {
        const index = line.indexOf("=");
        return [line.slice(0, index), line.slice(index + 1)];
      }),
  );
};
